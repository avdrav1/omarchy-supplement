#!/bin/bash
# Syncthing, Tailscale, fresh as the default editor, and the aerc/mbsync Gmail stack
source "$(dirname "$0")/../lib/common.sh"

# ── Syncthing ────────────────────────────────────────────────────────────────
# Its config and device identity (~/.local/state/syncthing) hold secrets and are
# per machine, so folders and devices are paired by hand at http://127.0.0.1:8384.
step "Syncthing"
user_service syncthing.service

# ── Tailscale ────────────────────────────────────────────────────────────────
# Gives each machine a stable 100.x address, which Syncthing uses to reach peers
# on other subnets directly instead of through public relays. `tailscale up`
# needs a browser sign-in, so it is a manual step.
step "Tailscale"
system_service tailscaled.service
if tailscale status &>/dev/null; then
  # Operator = this user may change prefs without sudo; the OmaScale bar widget
  # depends on it (exit node, up/down).
  [ "$(tailscale debug prefs 2>/dev/null | jq -r '.OperatorUser // ""')" = "$USER" ] ||
    sudo tailscale set --operator="$USER"
else
  note "not signed in yet: run  sudo tailscale up --operator=$USER"
fi

# ── Default editor: fresh ────────────────────────────────────────────────────
# Omarchy's EDITOR is `omarchy-launch-editor --inline`, which reads this state
# file -- so writing it redirects $EDITOR, SUPER+SHIFT+N and `omarchy default
# editor` at once. (omarchy-default-editor itself doesn't accept `fresh` yet.)
# The uwsm drop-in sets EDITOR/VISUAL for apps launched through uwsm, like aerc.
step "Default editor"
EDITOR_CMD="${EDITOR_CMD:-fresh}"
echo "$EDITOR_CMD" | put "$HOME/.local/state/omarchy/defaults/editor"
put "$HOME/.config/uwsm/env.d/50-supplement-editor" <<EOF
# GENERATED by omarchy-supplement (modules/50-services.sh) -- do not edit.
# Sourced by uwsm after Omarchy's env.d, so these win. Takes effect at next login.
export EDITOR=$EDITOR_CMD
export VISUAL=$EDITOR_CMD
EOF
systemctl --user set-environment EDITOR="$EDITOR_CMD" VISUAL="$EDITOR_CMD" 2>/dev/null || true

# ── Mail: aerc + mbsync + msmtp, Gmail over OAuth2 ───────────────────────────
# Configs come from the dotfiles `aerc-mail` package (so this runs after the
# dotfiles module). No secrets there: mbsync and msmtp get a fresh token at run
# time from `oama access <addr>`, and oama keeps its tokens GPG-encrypted.
step "Mail"
pkg aerc isync msmtp pass w3m oama-bin cyrus-sasl-xoauth2-git

ISYNCRC="$HOME/.config/isyncrc"
mkdir -p "$HOME/.local/share/mail"
# mbsync creates mailbox folders but not each account's top-level store dir.
[ -f "$ISYNCRC" ] && awk '/^Path /{print $2}' "$ISYNCRC" | sed "s#^~#$HOME#" | xargs -r mkdir -p

# oama encrypts tokens to this key. Passphraseless on purpose: the disk is LUKS
# encrypted, and a passphrase would make the 5-minute mbsync timer prompt.
GPG_UID="${GPG_UID:-Av <av@lab828.com>}"
if ! gpg --list-secret-keys "$GPG_UID" &>/dev/null; then
  gpg --batch --pinentry-mode loopback --passphrase '' --quick-generate-key "$GPG_UID" default default never
fi
if [ ! -f "$HOME/.password-store/.gpg-id" ]; then
  pass init "$(gpg --list-secret-keys --with-colons "$GPG_UID" | awk -F: '/^fpr:/{print $10; exit}')"
fi

if [ -e "$HOME/.config/systemd/user/mbsync.timer" ]; then
  systemctl --user daemon-reload
  user_service mbsync.timer
else
  warn "mbsync.timer missing -- run ./setup dotfiles first"
fi

# Report which accounts still need the one-time OAuth sign-in.
if [ -f "$ISYNCRC" ]; then
  for addr in $(grep -oE 'oama access [^"]+' "$ISYNCRC" | awk '{print $3}' | sort -u); do
    oama access "$addr" &>/dev/null || note "needs sign-in: oama authorize google $addr"
  done
fi
