#!/bin/bash
# Hyprland overrides (config/hypr), per-machine display scale, and the scroll-overview plugin
source "$(dirname "$0")/../lib/common.sh"

HYPR="$HOME/.config/hypr"
[ -f "$HYPR/hyprland.lua" ] || die "no $HYPR/hyprland.lua -- is this Omarchy with the Lua config?"

# ── Overrides ────────────────────────────────────────────────────────────────
# Hyprland's package.path covers ~/.config/?.lua, so linking config/hypr to
# ~/.config/supplement is all the wiring require("supplement.x") needs. The
# entry point is reached with dofile, not require: require() caches, and
# Hyprland only clears its own module prefixes on reload (see config/hypr/init.lua).
step "Overrides"
ln -sfn "$CONFIG/hypr" "$HOME/.config/supplement"
ENTRY_LINE='dofile(os.getenv("HOME") .. "/.config/supplement/init.lua")'
if ! grep -Fq "$ENTRY_LINE" "$HYPR/hyprland.lua"; then
  # Appended last, so it overrides Omarchy's defaults.
  printf '\n-- omarchy-supplement overrides (must come last).\n%s\n' "$ENTRY_LINE" >>"$HYPR/hyprland.lua"
  note "added the supplement entry to hyprland.lua"
fi

# ── Display scale ────────────────────────────────────────────────────────────
# Scale can't be set with hl.monitor: Omarchy's monitor-watch daemon re-applies
# the internal display's scale every 2s, parsing it out of monitors.lua with
#   sed -n 's/^local omarchy_monitor_scale = //p'
# and falling back to 2 when that isn't a bare number. So monitors.lua is
# generated from this machine's host file, keeping that exact line.
step "Display scale"
HOST=$(hostname)
HOSTFILE="$CONFIG/hypr/hosts/$HOST.lua"
if [ ! -f "$HOSTFILE" ]; then
  cp "$CONFIG/hypr/hosts/default.lua" "$HOSTFILE"
  warn "created config/hypr/hosts/$HOST.lua with scale 1 -- set the real scale, re-run, and commit it"
fi
pkg lua
SCALE=$(lua -e "print(assert(dofile('$HOSTFILE')).scale)")
GDK_SCALE=$(lua -e "print(assert(dofile('$HOSTFILE')).gdk_scale or 1)")
[[ $SCALE =~ ^[0-9]+([.][0-9]+)?$ ]] || die "scale '$SCALE' in $HOSTFILE must be a bare number"
put "$HYPR/monitors.lua" <<EOF
-- GENERATED by omarchy-supplement (modules/40-hyprland.sh) -- do not edit.
-- Source: config/hypr/hosts/$HOST.lua. Change the scale there and run ./setup hyprland.
--
-- Keep the \`local omarchy_monitor_scale = <number>\` line in exactly this shape:
-- Omarchy's monitor-watch daemon greps it every 2s to re-apply the scale.

local omarchy_gdk_scale = $GDK_SCALE
local omarchy_monitor_scale = $SCALE

hl.env("GDK_SCALE", tostring(omarchy_gdk_scale))
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = omarchy_monitor_scale })
EOF

# ── scroll-overview plugin (hyprpm) ──────────────────────────────────────────
# A workspace overview driven by touchpad scroll (ALT+`), configured in
# config/hypr/scrolloverview.lua. hyprpm compiles it against the installed
# Hyprland, so every Hyprland upgrade needs `hyprpm update && hyprpm reload`;
# the pacman hook below prints that reminder. hyprpm sudo-elevates itself to
# write /var/cache/hyprpm, so this part may prompt.
step "scroll-overview plugin"
PLUGIN_REPO="https://github.com/yayuuu/hyprland-scroll-overview"
PLUGIN_NAME="scrolloverview"

pkg hyprpm cmake meson ninja cpio git
command -v gcc &>/dev/null && command -v make &>/dev/null || pkg base-devel

SUDO=1 put /etc/pacman.d/hooks/hyprpm-plugins.hook <"$CONFIG/pacman/hyprpm-plugins.hook"

# hyprpm refuses every operation until its headers match the running Hyprland,
# and `hyprpm update` trusts its own state.toml hash -- which has been seen ahead
# of the headers actually on disk, producing a plugin Hyprland rejects with
# "Version mismatch". Compare the headers' version.h with what Hyprland was
# built against, and force a full rebuild when they differ.
vh=$(find /var/cache/hyprpm/"$USER"/headersRoot -name version.h -path '*hyprland/src/*' 2>/dev/null | head -1)
built=$(hyprctl version -j 2>/dev/null | jq -r '[.commit, .buildAquamarine, .buildHyprutils, .buildHyprlang, .buildHyprcursor, .buildHyprgraphics] | join(" ")' 2>/dev/null || true)
headers=
if [ -n "$vh" ]; then
  headers=$(for k in GIT_COMMIT_HASH AQUAMARINE_VERSION HYPRUTILS_VERSION HYPRLANG_VERSION HYPRCURSOR_VERSION HYPRGRAPHICS_VERSION; do
    sed -n "s/^#define $k *\"\(.*\)\"/\1/p" "$vh"
  done | paste -sd' ')
fi
if [ -n "$headers" ] && [ -n "$built" ] && [ "$headers" != "$built" ]; then
  note "hyprpm headers are stale; forcing a rebuild"
  hyprpm update -f
else
  hyprpm update
fi

if ! hyprpm list 2>/dev/null | grep -q "$PLUGIN_NAME"; then
  # Without a commit pin for the running Hyprland (common: Arch ships releases
  # faster than upstream pins them), hyprpm refuses to add. Building `main`
  # explicitly ignores the pins.
  hyprpm add "$PLUGIN_REPO" || hyprpm add "$PLUGIN_REPO" main
fi
hyprpm enable "$PLUGIN_NAME"
in_session && hyprpm reload -n
true
